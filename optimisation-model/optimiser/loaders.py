# Tracker column headings, as they appear in the cleaned export. Kept in one place because
# the source file is regenerated by hand and the headings have moved before.
_COL_NAME = "Project Short title"
_COL_ONCOLOGY = "Oncology trial"
_COL_ASEPTIC = "Aseptic Trial"
_COL_HRA = "HRA Approval Date"
_COL_SITE_SELECTED = "Project site date site selected"
_COL_NOTIFIED = "Pharmacy notified by RSG- start review"
_COL_GREENLIGHT = "Pharmacy Greenlight Approval"


def _parse_date(raw: str | None) -> datetime.date | None:
    """Tracker dates are ISO or blank. Anything else is reported rather than guessed at."""
    if not raw or not raw.strip():
        return None
    try:
        return datetime.date.fromisoformat(raw.strip()[:10])
    except ValueError:
        logger.warning("Unreadable date %r, treated as missing.", raw)
        return None


def _parse_flag(raw: str | None) -> bool:
    """The tracker uses Y and N. Blank is read as N."""
    return bool(raw) and raw.strip().upper().startswith("Y")


def load_demo_cases() -> list[Case]:
    """The 16-trial demonstration caseload.

    The clock anchor is carried as an HRA approval date computed from the per-trial gap, which
    keeps a single derivation path in `data.enrich` rather than a special case for the demo.
    """
    cases: list[Case] = []
    for name, value, prescription, aseptic, notified_iso, gap in DEMO_TRIALS:
        notified = datetime.date.fromisoformat(notified_iso)
        cases.append(
            Case(
                name=name,
                prescription=prescription,
                aseptic=aseptic,
                hra_approval=notified - datetime.timedelta(days=gap),
                site_selected=None,
                notified=notified,
                value=value,
            )
        )
    return cases


def load_tracker_cases(path: Path | str | None = None) -> list[Case]:
    """Cases from the cleaned CTIMP tracker.

    Rows carrying a greenlight date are kept here and dropped as complete by `data.enrich`, so
    the whole file can be passed in without filtering it first.

    Args:
        path: CSV to read. Defaults to the cleaned export of 2 August 2026.

    Returns:
        One case per row, with `value` None throughout because the tracker holds no scores.

    Raises:
        FileNotFoundError: If the CSV is missing.
        ValueError: If the expected name column is absent, which means the export changed.
    """
    csv_path = Path(path) if path else TRACKER_CSV
    if not csv_path.exists():
        raise FileNotFoundError(f"Tracker CSV not found at {csv_path}")

    with csv_path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None or _COL_NAME not in reader.fieldnames:
            raise ValueError(
                f"{csv_path.name} has no {_COL_NAME!r} column. Columns found: "
                f"{reader.fieldnames}"
            )
        cases = [
            Case(
                name=(row.get(_COL_NAME) or "").strip(),
                prescription=_parse_flag(row.get(_COL_ONCOLOGY)),
                aseptic=_parse_flag(row.get(_COL_ASEPTIC)),
                hra_approval=_parse_date(row.get(_COL_HRA)),
                site_selected=_parse_date(row.get(_COL_SITE_SELECTED)),
                notified=_parse_date(row.get(_COL_NOTIFIED)),
                value=None,
                greenlight=_parse_date(row.get(_COL_GREENLIGHT)),
            )
            for row in reader
            if (row.get(_COL_NAME) or "").strip()
        ]

    logger.info("Loaded %d tracker rows from %s.", len(cases), csv_path.name)
    return cases
